// Generates lib/src/tokens/tokens.g.dart from tokens/tokens.json.
//
// tokens/tokens.json is a byte-identical copy of the root docs/design/tokens.json
// (the canonical file); edit the root generator, copy the file here, then run
// `dart run tool/gen_tokens.dart` from packages/fynona_ui.
import 'dart:convert';
import 'dart:io';

const _themes = ['light', 'dark', 'hcLight', 'hcDark'];

/// Groups whose number and dimension tokens become `FynonaTokens` constants.
const _numericGroups = [
  'opacity',
  'glass',
  'radius',
  'space',
  'size',
  'borderWidth',
  'font',
  'textScale',
  'motion',
  'gesture',
  'breakpoint',
  'layout',
];

void main() {
  final json = jsonDecode(
    File('tokens/tokens.json').readAsStringSync(),
  ) as Map<String, Object?>;
  File('lib/src/tokens/tokens.g.dart').writeAsStringSync(generateTokens(json));
}

/// Dart source for the token set [json] (DTCG format).
String generateTokens(Map<String, Object?> json) {
  final tokens = _Tokens(json);
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from tokens/tokens.json.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln("import 'package:material_ui/material_ui.dart';")
    ..writeln();
  _colors(tokens, out);
  _numbers(tokens, out);
  _typography(tokens, out);
  return out.toString();
}

void _colors(_Tokens tokens, StringBuffer out) {
  final theme = tokens.group(['color', 'light']);
  final roles = <(String, List<String>)>[];
  for (final group in theme.keys.where((k) => !k.startsWith(r'$'))) {
    for (final role in (theme[group] as Map<String, Object?>).keys) {
      if (role.startsWith(r'$')) continue;
      roles.add((_camel([group, role]), [group, role]));
    }
  }

  out
    ..writeln(
      '/// Every colour role of one theme of `tokens.json` (`color.<theme>`).',
    )
    ..writeln('@immutable')
    ..writeln('class FynonaColors extends ThemeExtension<FynonaColors> {')
    ..writeln('  const FynonaColors({');
  for (final (name, _) in roles) {
    out.writeln('    required this.$name,');
  }
  out.writeln('  });');
  for (final themeName in _themes) {
    out
      ..writeln()
      ..writeln('  /// `color.$themeName`.')
      ..writeln('  static const $themeName = FynonaColors(');
    for (final (name, path) in roles) {
      final hex = tokens.colorHex(['color', themeName, ...path]);
      out.writeln('    $name: Color($hex),');
    }
    out.writeln('  );');
  }
  for (final (name, path) in roles) {
    final description = tokens.description(['color', 'light', ...path]);
    out.writeln();
    if (description != null) out.writeln('  /// ${_doc(description)}');
    out.writeln('  final Color $name;');
  }
  out
    ..writeln()
    ..writeln('  @override')
    ..writeln('  FynonaColors copyWith({');
  for (final (name, _) in roles) {
    out.writeln('    Color? $name,');
  }
  out.writeln('  }) => FynonaColors(');
  // Lines are wrapped the way `dart format` wraps them, so the output is
  // already formatted.
  for (final (name, _) in roles) {
    final line = '    $name: $name ?? this.$name,';
    out.writeln(
      line.length <= 80 ? line : '    $name:\n        $name ?? this.$name,',
    );
  }
  out
    ..writeln('  );')
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  FynonaColors lerp(ThemeExtension<FynonaColors>? other, double t) {',
    )
    ..writeln('    if (other is! FynonaColors) return this;')
    ..writeln('    return FynonaColors(');
  for (final (name, _) in roles) {
    final line = '      $name: Color.lerp($name, other.$name, t)!,';
    out.writeln(
      line.length <= 80
          ? line
          : '      $name: Color.lerp(\n'
                '        $name,\n'
                '        other.$name,\n'
                '        t,\n'
                '      )!,',
    );
  }
  out
    ..writeln('    );')
    ..writeln('  }')
    ..writeln('}');
  for (final (group, className) in [
    ('brand', 'FynonaBrandColors'),
    ('shadow', 'FynonaShadowColors'),
  ]) {
    out
      ..writeln()
      ..writeln('/// Theme-independent colours (`color.$group`).')
      ..writeln('abstract final class $className {');
    final colors = tokens.group(['color', group]);
    for (final key in colors.keys.where((k) => !k.startsWith(r'$'))) {
      final hex = tokens.colorHex(['color', group, key]);
      out.writeln('  static const Color $key = Color($hex);');
    }
    out.writeln('}');
  }
}

void _numbers(_Tokens tokens, StringBuffer out) {
  out
    ..writeln()
    ..writeln('/// Number, dimension (logical pixels) and duration tokens.')
    ..write('abstract final class FynonaTokens {');
  void walk(List<String> path, Map<String, Object?> node, String? type) {
    final groupType = node[r'$type'] as String? ?? type;
    if (node.containsKey(r'$value')) {
      final line = _numberConstant(tokens, path, node, groupType);
      if (line != null) {
        final description = node[r'$description'] as String?;
        out.writeln();
        if (description != null) out.writeln('  /// ${_doc(description)}');
        out.writeln(line);
      }
      return;
    }
    for (final MapEntry(:key, :value) in node.entries) {
      if (key.startsWith(r'$') || value is! Map<String, Object?>) continue;
      walk([...path, key], value, groupType);
    }
  }

  for (final group in _numericGroups) {
    walk([group], tokens.group([group]), null);
  }
  out.writeln('}');
}

String? _numberConstant(
  _Tokens tokens,
  List<String> path,
  Map<String, Object?> node,
  String? groupType,
) {
  final type = node[r'$type'] as String? ?? groupType;
  final value = tokens.resolve(node[r'$value']);
  final name = _camel(path);
  switch (type) {
    case 'number' when value is num:
      return '  static const $name = ${_num(value)};';
    case 'fontWeight' when value is num:
      return '  static const $name = FontWeight(${value.toInt()});';
    case 'dimension' when value is Map && value['unit'] == 'px':
      return '  static const $name = ${_num(value['value'] as num)};';
    case 'duration' when value is Map && value['unit'] == 'ms':
      final ms = (value['value'] as num).toInt();
      return '  static const $name = Duration(milliseconds: $ms);';
  }
  return null;
}

void _typography(_Tokens tokens, StringBuffer out) {
  out
    ..writeln()
    ..writeln(
      '/// Composite text styles (`typography`), bundled Inter, tnum + lnum.',
    )
    ..writeln('abstract final class FynonaTypography {')
    ..writeln(
      "  /// Font family of `font.family.base`, bundled in this package.",
    )
    ..writeln("  static const String fontFamily = 'Inter';")
    ..writeln()
    ..writeln('  /// Package that bundles [fontFamily].')
    ..writeln("  static const String fontPackage = 'fynona_ui';")
    ..writeln()
    ..writeln('  static const List<FontFeature> _features = [')
    ..writeln('    FontFeature.tabularFigures(),')
    ..writeln('    FontFeature.liningFigures(),')
    ..writeln('  ];');
  final group = tokens.group(['typography']);
  for (final key in group.keys.where((k) => !k.startsWith(r'$'))) {
    final node = group[key] as Map<String, Object?>;
    final value = node[r'$value'] as Map<String, Object?>;
    final family = tokens.resolve(value['fontFamily']) as List<Object?>;
    final size = tokens.resolve(value['fontSize']) as Map<String, Object?>;
    final weight = tokens.resolve(value['fontWeight']) as num;
    final spacing =
        tokens.resolve(value['letterSpacing']) as Map<String, Object?>;
    final height = tokens.resolve(value['lineHeight']) as num;
    final description = node[r'$description'] as String?;
    out.writeln();
    if (description != null) out.writeln('  /// ${_doc(description)}');
    out.writeln('  static const TextStyle $key = TextStyle(');
    if (family.first == 'Inter') {
      out
        ..writeln('    fontFamily: fontFamily,')
        ..writeln('    package: fontPackage,');
    } else {
      out
        ..writeln("    fontFamily: '${family.first}',")
        ..writeln(
          "    fontFamilyFallback: [${family.skip(1).map((f) => "'$f'").join(', ')}],",
        );
    }
    out
      ..writeln('    fontSize: ${_num(size['value'] as num)},')
      ..writeln('    fontWeight: FontWeight(${weight.toInt()}),')
      ..writeln('    letterSpacing: ${_num(spacing['value'] as num)},')
      ..writeln('    height: ${_num(height)},')
      ..writeln('    fontFeatures: _features,')
      ..writeln('  );');
  }
  out.writeln('}');
}

String _num(num value) {
  final d = value.toDouble();
  return d == d.roundToDouble() ? d.toStringAsFixed(1) : d.toString();
}

String _camel(List<String> parts) {
  final b = StringBuffer(parts.first);
  for (final p in parts.skip(1)) {
    b
      ..write(p[0].toUpperCase())
      ..write(p.substring(1));
  }
  return b.toString();
}

/// First sentence of a token description, safe for a one-line doc comment.
String _doc(String description) {
  final line = description.split('\n').first;
  final end = line.indexOf('. ');
  return end < 0 ? line : line.substring(0, end + 1);
}

class _Tokens {
  _Tokens(this.json);

  final Map<String, Object?> json;

  Map<String, Object?> group(List<String> path) {
    Object? node = json;
    for (final p in path) {
      node = (node as Map<String, Object?>)[p];
    }
    return node as Map<String, Object?>;
  }

  String? description(List<String> path) =>
      group(path)[r'$description'] as String?;

  /// Follows `{group.token}` aliases to a concrete value.
  Object? resolve(Object? value) {
    var current = value;
    while (current is String &&
        current.startsWith('{') &&
        current.endsWith('}')) {
      current = group(
        current.substring(1, current.length - 1).split('.'),
      )[r'$value'];
    }
    return current;
  }

  /// `0xAARRGGBB` of a colour token (DTCG colour object, alpha 0…1).
  String colorHex(List<String> path) {
    final value = resolve(group(path)[r'$value']) as Map<String, Object?>;
    final hex = colorArgb(value).toRadixString(16).toUpperCase();
    return '0x${hex.padLeft(8, '0')}';
  }
}

/// ARGB of a DTCG colour object: `hex` for RGB, `alpha` (default 1) for A.
int colorArgb(Map<String, Object?> value) {
  final rgb = int.parse((value['hex'] as String).substring(1), radix: 16);
  final alpha = ((value['alpha'] as num? ?? 1) * 255).round();
  return (alpha << 24) | rgb;
}
